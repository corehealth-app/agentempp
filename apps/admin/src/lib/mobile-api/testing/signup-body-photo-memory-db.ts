/**
 * TEST SUPPORT — the database behind the routes of the body photos of the
 * sign-up, in memory, at the level of the database client: the real route
 * wrapper, the real handlers and the real adapters run on top of it.
 *
 * It answers only what those routes are expected to ask. Any other table or
 * function throws, so a query nobody declared fails the test that made it.
 * Every call is written to `operations`, in order, and to `calls`, with what
 * it carried.
 *
 * What is modelled, each after the migration that defines it:
 *  - authentication of the route wrapper: the access token, the account
 *    bootstrap and the `users` row;
 *  - the idempotency ledger and its three functions
 *    (20260720130537_mobile_api_idempotency.sql);
 *  - `legal_documents`, `user_legal_acceptances`, the receipts of the legal
 *    acceptance and the two functions `get_mobile_legal_document` and
 *    `accept_mobile_legal_document`
 *    (20260722172356_bodyflow_routine_items_domain.sql and
 *    20260722191125_bodyflow_routine_items_api.sql);
 *  - `media_assets` with its constraints and its status-transition trigger,
 *    and the private storage buckets
 *    (20260720153510_bodyflow_secure_media_storage.sql);
 *  - the two onboarding columns of `user_profiles`.
 *
 * A statement that breaks a constraint or the trigger changes nothing, as in
 * the database: an UPDATE over several rows is all or nothing.
 *
 * No database was read to write this file.
 */
