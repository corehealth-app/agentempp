  /** The locale the two functions read: an active account in one of the two languages. */
  private legalLocale(userId: unknown): string | null {
    const account = this.accounts.find((entry) => entry.id === userId)
    if (!account || (account.status ?? 'active') !== 'active') return null
    const locale = account.locale === undefined ? 'pt-BR' : account.locale
    return locale === 'pt-BR' || locale === 'en-US' ? locale : null
  }

  private currentLegalDocument(documentKey: unknown, locale: string): MemoryLegalDocument | null {
    const now = this.now().getTime()
    const [current] = this.legalDocuments
      .filter(
        (row) =>
          row.document_key === documentKey &&
          row.locale === locale &&
          new Date(row.required_from).getTime() <= now,
      )
      .sort(
        (left, right) =>
          new Date(right.required_from).getTime() - new Date(left.required_from).getTime() ||
          new Date(right.created_at).getTime() - new Date(left.created_at).getTime() ||
          right.id.localeCompare(left.id),
      )
    return current ?? null
  }

  private getLegalDocument(params: Row): DbResult {
    const key = params.p_document_key
    if (!params.p_user_id || typeof key !== 'string' || !/^[a-z][a-z0-9_]{0,99}$/.test(key)) {
      return raise('22023', 'invalid_legal_document_request')
    }
    const locale = this.legalLocale(params.p_user_id)
    if (locale === null) return raise('P0002', 'legal_document_not_available')
    const document = this.currentLegalDocument(key, locale)
    if (!document) return raise('P0002', 'legal_document_not_available')
    return {
      data: {
        document_key: document.document_key,
        version: document.version,
        locale: document.locale,
        body: document.body,
        body_hash: document.body_hash,
        required_from: document.required_from,
      },
      error: null,
    }
  }

  private acceptLegalDocument(params: Row): DbResult {
    const userId = params.p_user_id
    const key = params.p_document_key
    const version = params.p_version
    const bodyHash = params.p_body_hash
    const idempotencyKey = params.p_idempotency_key
    if (!userId || key == null || version == null || bodyHash == null) {
      return raise('22023', 'invalid_legal_acceptance')
    }
    const requestHash = sha256Hex(`${key}:${version}:${bodyHash}`)
    if (
      typeof idempotencyKey !== 'string' ||
      idempotencyKey.length < 8 ||
      idempotencyKey.length > 128 ||
      !/^[A-Za-z0-9._:-]+$/.test(idempotencyKey)
    ) {
      return raise('22023', 'invalid_routine_mutation_identity')
    }
    const receipt = this.mutationReceipts.find(
      (row) => row.user_id === userId && row.idempotency_key === idempotencyKey,
    )
    if (receipt) {
      if (receipt.operation !== 'legal_acceptance' || receipt.request_hash !== requestHash) {
        return raise('23505', 'routine_mutation_idempotency_conflict')
      }
      return { data: { ...receipt.result_payload }, error: null }
    }
    if (
      typeof key !== 'string' ||
      !/^[a-z][a-z0-9_]{0,99}$/.test(key) ||
      typeof version !== 'string' ||
      !/^[A-Za-z0-9._-]{1,64}$/.test(version) ||
      typeof bodyHash !== 'string' ||
      !/^[0-9a-f]{64}$/.test(bodyHash)
    ) {
      return raise('22023', 'invalid_legal_acceptance')
    }
    const locale = this.legalLocale(userId)
    if (locale === null) return raise('P0002', 'legal_document_not_available')
    const document = this.currentLegalDocument(key, locale)
    if (!document || document.version !== version || document.body_hash !== bodyHash) {
      return raise('22023', 'legal_document_version_mismatch')
    }
    let acceptance = this.legalAcceptances.find(
      (row) =>
        row.user_id === userId && row.document_key === key && row.version === document.version,
    )
    if (!acceptance) {
      acceptance = {
        user_id: String(userId),
        legal_document_id: document.id,
        document_key: document.document_key,
        version: document.version,
        locale: document.locale,
        body_hash: document.body_hash,
        accepted_at: databaseTimestamp(this.now()),
      }
      this.legalAcceptances.push(acceptance)
    }
    const result = {
      document_key: document.document_key,
      accepted_version: document.version,
      accepted_at: acceptance.accepted_at,
    }
    this.mutationReceipts.push({
      user_id: String(userId),
      idempotency_key: idempotencyKey,
      operation: 'legal_acceptance',
      request_hash: requestHash,
      result_payload: result,
    })
    return { data: { ...result }, error: null }
  }

