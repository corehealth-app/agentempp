  private claimRequest(params: Row): DbResult {
    const now = this.now().getTime()
    const day = 24 * 60 * 60 * 1000
    const existing = this.ledger.find(
      (row) => row.user_id === params.p_user_id && row.idempotency_key === params.p_idempotency_key,
    )
    const method = String(params.p_request_method).toUpperCase()
    const route = String(params.p_request_route)
    const hash = String(params.p_request_hash).toLowerCase()
    if (!existing) {
      const row: LedgerRow = {
        id: this.nextId('claim'),
        user_id: String(params.p_user_id),
        idempotency_key: String(params.p_idempotency_key),
        request_method: method,
        request_route: route,
        request_hash: hash,
        state: 'processing',
        response_status: null,
        response_body: null,
        attempt_count: 1,
        updated_at: now,
        expires_at: now + day,
      }
      this.ledger.push(row)
      return { data: { action: 'claimed', claim_id: row.id }, error: null }
    }
    if (existing.expires_at <= now) {
      Object.assign(existing, {
        request_method: method,
        request_route: route,
        request_hash: hash,
        state: 'processing',
        response_status: null,
        response_body: null,
        attempt_count: 1,
        updated_at: now,
        expires_at: now + day,
      })
      return { data: { action: 'claimed', claim_id: existing.id }, error: null }
    }
    if (
      existing.request_method !== method ||
      existing.request_route !== route ||
      existing.request_hash !== hash
    ) {
      return { data: { action: 'conflict' }, error: null }
    }
    if (existing.state === 'completed') {
      return {
        data: {
          action: 'replay',
          response_status: existing.response_status,
          response_body: existing.response_body,
        },
        error: null,
      }
    }
    if (existing.state === 'processing' && existing.updated_at > now - 10 * 60 * 1000) {
      return { data: { action: 'in_progress' }, error: null }
    }
    Object.assign(existing, {
      state: 'processing',
      response_status: null,
      response_body: null,
      attempt_count: existing.attempt_count + 1,
      updated_at: now,
      expires_at: now + day,
    })
    return { data: { action: 'claimed', claim_id: existing.id }, error: null }
  }

  private completeRequest(params: Row): DbResult {
    const row = this.ledger.find(
      (entry) =>
        entry.id === params.p_claim_id &&
        entry.user_id === params.p_user_id &&
        entry.state === 'processing',
    )
    if (!row) return { data: false, error: null }
    row.state = 'completed'
    row.response_status = Number(params.p_response_status)
    // What the ledger keeps is what was handed to it, as JSON.
    row.response_body = JSON.parse(JSON.stringify(params.p_response_body))
    row.updated_at = this.now().getTime()
    return { data: true, error: null }
  }

  private failRequest(params: Row): DbResult {
    const row = this.ledger.find(
      (entry) =>
        entry.id === params.p_claim_id &&
        entry.user_id === params.p_user_id &&
        entry.state === 'processing',
    )
    if (!row) return { data: false, error: null }
    row.state = 'failed'
    row.response_status = null
    row.response_body = null
    row.updated_at = this.now().getTime()
    return { data: true, error: null }
  }
